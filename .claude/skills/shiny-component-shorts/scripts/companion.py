#!/usr/bin/env python3
"""Record the other orientation of a finished demo from the same actions and narration.

Every generated video ships as a pair: vertical (9:16) and horizontal (16:9).
The companion is a sidecar project in `<demo>/artifacts/<orientation>/` that
reuses the demo's app, `actions.yaml`, and narration with only the
orientation flipped. Cue actions anchor every reaction to the same spoken
words, so the narration stays in sync in both videos without retiming.

The finished companion is also copied up beside the primary video as
`artifacts/final_with_audio-<orientation>.mp4` (or `demo-<orientation>.mp4`
for a silent video).
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

SCRIPTS_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPTS_DIR))
import build_cache  # noqa: E402

OTHER = {"vertical": "horizontal", "horizontal": "vertical"}
NARRATION_FILES = ("narration.txt", "narration.wav", "narration-timing.json")


def primary_orientation(project_dir: Path) -> str:
    config = yaml.safe_load((project_dir / "actions.yaml").read_text(encoding="utf-8")) or {}
    orientation = config.get("orientation", "vertical")
    if orientation not in OTHER:
        raise ValueError(f"Unsupported orientation in actions.yaml: {orientation}")
    return orientation


def companion_dir(project_dir: Path) -> Path:
    return project_dir / "artifacts" / OTHER[primary_orientation(project_dir)]


def _write_if_changed(path: Path, text: str) -> None:
    if not path.is_file() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")


def _copy_if_changed(source: Path, target: Path) -> None:
    if not target.is_file() or source.read_bytes() != target.read_bytes():
        shutil.copy2(source, target)


def prepare_companion(project_dir: Path) -> Path:
    """Write the companion's actions, narration, and settings; return its directory."""
    project_dir = project_dir.resolve()
    config = yaml.safe_load((project_dir / "actions.yaml").read_text(encoding="utf-8"))
    if not isinstance(config, dict):
        raise ValueError(f"{project_dir}/actions.yaml must be a mapping")
    target = companion_dir(project_dir)
    artifacts = target / "artifacts"
    artifacts.mkdir(parents=True, exist_ok=True)
    config["orientation"] = OTHER[config.get("orientation", "vertical")]
    _write_if_changed(
        target / "actions.yaml",
        "# Generated by companion.py from ../../actions.yaml; edit that file instead.\n"
        + yaml.safe_dump(config, sort_keys=False, allow_unicode=True, width=4096),
    )
    for name in NARRATION_FILES:
        source = project_dir / "artifacts" / name
        if source.is_file():
            _copy_if_changed(source, artifacts / name)
        else:
            (artifacts / name).unlink(missing_ok=True)
    settings_path = project_dir / "tts-settings.json"
    if settings_path.is_file():
        settings = json.loads(settings_path.read_text(encoding="utf-8"))
        for key in ("music_bed", "audio_source", "reference_voice"):
            if key in settings and not Path(str(settings[key])).expanduser().is_absolute():
                settings[key] = str((project_dir / str(settings[key])).resolve())
        _write_if_changed(target / "tts-settings.json", json.dumps(settings, indent=2) + "\n")
    else:
        (target / "tts-settings.json").unlink(missing_ok=True)
    return target


def detect_app_type(app_dir: Path) -> str:
    if (app_dir / "app.py").is_file():
        return "python"
    if (app_dir / "app.R").is_file():
        return "r"
    raise RuntimeError(f"No app.py or app.R found in {app_dir}")


def is_narrated(project_dir: Path) -> bool:
    return (project_dir / "artifacts" / "narration.wav").is_file()


def deliverable(project_dir: Path) -> Path:
    """Where the finished companion video is published beside the primary one."""
    orientation = OTHER[primary_orientation(project_dir)]
    name = "final_with_audio" if is_narrated(project_dir) else "demo"
    return project_dir / "artifacts" / f"{name}-{orientation}.mp4"


def _run(command: list[str], label: str) -> None:
    completed = subprocess.run(command, capture_output=True, text=True)
    if completed.returncode != 0:
        output = (completed.stdout + completed.stderr).strip()
        raise RuntimeError(f"{label} failed:\n{output[-3000:]}")


def record_companion(
    project_dir: Path,
    app_dir: Path | None = None,
    port: int | None = None,
    force: bool = False,
    dry_run: bool = False,
) -> dict:
    """Prepare, record, merge, validate, and publish the companion orientation."""
    project_dir = project_dir.resolve()
    app_dir = (app_dir or project_dir).resolve()
    target = prepare_companion(project_dir)
    orientation = OTHER[primary_orientation(project_dir)]
    narrated = is_narrated(project_dir)
    record = [
        sys.executable, str(SCRIPTS_DIR / "record_demo.py"),
        "--project-dir", str(target), "--app-dir", str(app_dir),
        "--app-type", detect_app_type(app_dir),
        "--actions", str(target / "actions.yaml"), "--orientation", orientation,
        *(["--port", str(port)] if port else []),
    ]
    if dry_run:
        _run([*record, "--dry-run"], f"{orientation} preflight")
        return {"orientation": orientation, "dir": str(target), "status": "PREFLIGHT"}

    artifacts = target / "artifacts"
    inputs = build_cache.collect_project_inputs(
        app_dir,
        [
            target / "actions.yaml",
            *[artifacts / name for name in NARRATION_FILES if (artifacts / name).is_file()],
            *([target / "tts-settings.json"] if (target / "tts-settings.json").is_file() else []),
            SCRIPTS_DIR / "record_demo.py",
            SCRIPTS_DIR / "merge_audio.py",
            SCRIPTS_DIR / "validate_demo.py",
            SCRIPTS_DIR / "companion.py",
        ],
    )
    final = artifacts / ("final_with_audio.mp4" if narrated else "demo.mp4")
    published = deliverable(project_dir)
    if not force and build_cache.check_cache(target, "companion", inputs, [final, published]):
        return {"orientation": orientation, "dir": str(target), "video": str(published), "status": "CACHED"}

    _run(record, f"{orientation} recording")
    if narrated:
        merge = [sys.executable, str(SCRIPTS_DIR / "merge_audio.py"), "--project-dir", str(target)]
        settings_path = target / "tts-settings.json"
        settings = json.loads(settings_path.read_text(encoding="utf-8")) if settings_path.is_file() else {}
        if settings.get("audio_processing") == "preserve":
            merge.append("--preserve-audio")
        if settings.get("music_bed"):
            merge += ["--bed", str(settings["music_bed"])]
        _run(merge, f"{orientation} audio merge")
    _run(
        [
            sys.executable, str(SCRIPTS_DIR / "validate_demo.py"),
            "--project-dir", str(target), "--app-dir", str(app_dir),
            *(["--require-audio"] if narrated else []),
        ],
        f"{orientation} validation",
    )
    subprocess.run(
        [sys.executable, str(SCRIPTS_DIR / "review_frames.py"), "--project-dir", str(target)],
        capture_output=True,
    )
    shutil.copy2(final, published)
    build_cache.update_cache(target, "companion", inputs)
    return {
        "orientation": orientation,
        "dir": str(target),
        "video": str(published),
        "review_sheet": str(artifacts / "review.png"),
        "status": "SUCCESS",
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--project-dir", type=Path, required=True, help="The finished primary demo")
    parser.add_argument("--app-dir", type=Path, help="App directory when it differs from --project-dir")
    parser.add_argument("--port", type=int)
    parser.add_argument("--force", action="store_true", help="Ignore the companion cache")
    parser.add_argument("--dry-run", action="store_true", help="Preflight the companion only")
    args = parser.parse_args(argv)
    try:
        report = record_companion(args.project_dir, args.app_dir, args.port, args.force, args.dry_run)
    except (RuntimeError, ValueError, FileNotFoundError) as exc:
        print(exc, file=sys.stderr)
        return 1
    print(f"{report['orientation']} companion: {report['status']}")
    for key in ("video", "review_sheet", "dir"):
        if report.get(key):
            print(f"  {key}: {report[key]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
